#!/usr/bin/env node
/**
 * Renders the Chrome Web Store listing images and the site's social card.
 *
 * Each frame in store/frames/ is authored at its exact final pixel size and captured
 * with headless Chrome. Two of the screenshots embed the extension's *real* options
 * page and popup in an iframe rather than a pasted-in bitmap, so a listing image can
 * never show a UI the extension no longer has — which is the kind of drift that gets
 * an item pulled for "functionality does not match the description".
 *
 *   npm run store-assets
 *
 * Output: dist/store/. Re-run whenever the UI or the copy changes.
 */

import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, readdirSync, statSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const STAGE = join(ROOT, 'dist', 'store-frames');
const OUT = join(ROOT, 'dist', 'store');

/** Where Chrome lives, by platform. Override with CHROME=/path/to/chrome. */
const CHROME_CANDIDATES = [
  process.env.CHROME,
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/Applications/Chromium.app/Contents/MacOS/Chromium',
  '/usr/bin/google-chrome',
  '/usr/bin/google-chrome-stable',
  '/usr/bin/chromium',
  '/usr/bin/chromium-browser',
].filter(Boolean);

const chrome = CHROME_CANDIDATES.find((path) => existsSync(path));
if (!chrome) {
  console.error(
    'Could not find Chrome. Install it, or set CHROME=/path/to/chrome.\n' +
      'Tried:\n  ' + CHROME_CANDIDATES.join('\n  ')
  );
  process.exit(1);
}

/**
 * Frames to capture. Sizes are the Chrome Web Store's, and are not negotiable:
 *   screenshots     1280x800 (or 640x400), 1-5 of them, REQUIRED
 *   small promo     440x280, REQUIRED
 *   marquee promo   1400x560, optional (needed for the store homepage carousel)
 */
const FRAMES = [
  { file: 'shot-01-tabstrip.html', out: 'screenshot-1-tabstrip.png', width: 1280, height: 800 },
  { file: 'shot-02-settings.html', out: 'screenshot-2-settings.png', width: 1280, height: 800 },
  { file: 'shot-03-popup.html', out: 'screenshot-3-popup.png', width: 1280, height: 800 },
  { file: 'shot-04-styles.html', out: 'screenshot-4-styles.png', width: 1280, height: 800 },
  { file: 'shot-05-honest.html', out: 'screenshot-5-honest.png', width: 1280, height: 800 },
  { file: 'promo-small.html', out: 'promo-small-440x280.png', width: 440, height: 280 },
  { file: 'promo-marquee.html', out: 'promo-marquee-1400x560.png', width: 1400, height: 560 },
  { file: 'social.html', out: 'social-card-1200x630.png', width: 1200, height: 630 },
];

/**
 * A `chrome.*` stand-in so the real extension pages render outside the extension.
 * Only ever written into the throwaway staging directory — it is not shipped.
 */
const SHIM = `// Generated by scripts/make-store-assets.mjs — staging only, never shipped.
const store = {};
globalThis.chrome = {
  storage: {
    sync: {
      async get(key) { return key in store ? { [key]: store[key] } : {}; },
      async set(items) { Object.assign(store, items); },
    },
    onChanged: { addListener() {} },
  },
  runtime: { id: 'store-assets', openOptionsPage() {} },
  tabs: {
    async query() { return [{ id: 1, url: 'https://figma.com/file/demo', incognito: false }]; },
    async sendMessage() {
      const used = 812 * 1024 * 1024;
      const limit = 4 * 1024 * 1024 * 1024;
      return {
        ok: true, supported: true, origin: 'https://figma.com',
        reading: { used, total: used, limit, ratio: used / limit, at: Date.now() - 3000 },
        level: 'high', bucketized: false, iconBlocked: false, stale: false, hidden: false,
      };
    },
  },
};
`;

// ── stage ───────────────────────────────────────────────────────────────────

rmSync(STAGE, { recursive: true, force: true });
rmSync(OUT, { recursive: true, force: true });
mkdirSync(STAGE, { recursive: true });
mkdirSync(OUT, { recursive: true });

cpSync(join(ROOT, 'store', 'frames'), STAGE, { recursive: true });

const order = JSON.parse(readFileSync(join(ROOT, 'src', 'shared', '_order.json'), 'utf8')).files;
mkdirSync(join(STAGE, 'shared'), { recursive: true });
for (const file of order) {
  cpSync(join(ROOT, 'src', 'shared', file), join(STAGE, 'shared', file));
}

mkdirSync(join(STAGE, 'icons'), { recursive: true });
for (const icon of readdirSync(join(ROOT, 'src', 'icons'))) {
  cpSync(join(ROOT, 'src', 'icons', icon), join(STAGE, 'icons', icon));
}

// The real extension pages, with the chrome shim injected ahead of everything else.
writeFileSync(join(STAGE, 'shim.js'), SHIM);
for (const page of ['options', 'popup']) {
  cpSync(join(ROOT, 'src', page), join(STAGE, page), { recursive: true });

  const htmlPath = join(STAGE, page, `${page}.html`);
  const html = readFileSync(htmlPath, 'utf8');
  const firstScript = '<script src="../shared/constants.js"></script>';
  if (!html.includes(firstScript)) {
    console.error(`Could not find the shared-script block in src/${page}/${page}.html.`);
    process.exit(1);
  }
  writeFileSync(
    htmlPath,
    html.replace(firstScript, `<script src="../shim.js"></script>\n    ${firstScript}`)
  );
}

// ── capture ─────────────────────────────────────────────────────────────────

for (const frame of FRAMES) {
  const target = join(OUT, frame.out);
  execFileSync(
    chrome,
    [
      '--headless=new',
      '--disable-gpu',
      '--hide-scrollbars',
      '--force-device-scale-factor=1',
      '--default-background-color=00000000',
      // The frames draw canvases and, in two cases, load an iframe. Give the renderer a
      // beat to settle so nothing is captured half-painted.
      '--virtual-time-budget=3000',
      `--window-size=${frame.width},${frame.height}`,
      `--screenshot=${target}`,
      `file://${join(STAGE, frame.file)}`,
    ],
    { stdio: ['ignore', 'ignore', 'pipe'] }
  );

  if (!existsSync(target)) {
    console.error(`Chrome produced no output for ${frame.file}`);
    process.exit(1);
  }

  const { width, height } = pngSize(readFileSync(target));
  const ok = width === frame.width && height === frame.height;
  console.log(
    `${ok ? '  ok' : ' BAD'}  ${frame.out.padEnd(30)} ${width}x${height}` +
      (ok ? '' : `  (expected ${frame.width}x${frame.height})`)
  );
  if (!ok) process.exitCode = 1;
}

// The 128x128 store icon is a required asset and already exists — copy it in so the
// whole listing lives in one directory.
cpSync(join(ROOT, 'src', 'icons', 'icon-128.png'), join(OUT, 'store-icon-128.png'));
console.log(`  ok  ${'store-icon-128.png'.padEnd(30)} 128x128`);

// The site's Open Graph image is the same picture, but re-encoded as JPEG: the PNG is
// a 350 KB mostly-gradient bitmap and the site should not carry that. Quality 82 on a
// 1200x630 gradient is visually identical and roughly a tenth of the size.
const socialPng = join(OUT, 'social-card-1200x630.png');
const socialJpg = join(ROOT, 'site', 'social-card.jpg');
try {
  execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '82', socialPng, '--out', socialJpg], {
    stdio: ['ignore', 'ignore', 'pipe'],
  });
  const before = statSync(socialPng).size;
  const after = statSync(socialJpg).size;
  console.log(`  ok  ${'site/social-card.jpg'.padEnd(30)} ${(after / 1024).toFixed(0)} KB (from ${(before / 1024).toFixed(0)} KB PNG)`);
} catch {
  // `sips` is macOS-only. Fall back to the PNG rather than failing the whole run.
  cpSync(socialPng, join(ROOT, 'site', 'social-card.png'));
  console.log('  --  sips unavailable; copied the PNG social card instead of a JPEG');
}

const total = readdirSync(OUT).reduce((sum, f) => sum + statSync(join(OUT, f)).size, 0);
console.log(`\nwrote ${relative(ROOT, OUT)}/  (${(total / 1024).toFixed(0)} KB)`);

/** Read width/height straight out of the PNG IHDR, to verify the capture size. */
function pngSize(buffer) {
  return { width: buffer.readUInt32BE(16), height: buffer.readUInt32BE(20) };
}
